const BUILDERS = {
  trigger: { build: buildGuidedLoadTriggerFrame, expected: TRIGGER_FRAMES },
  statusRead: { build: buildGuidedLoadStatusReadFrame, expected: STATUS_READ_FRAMES },
  exit: { build: buildGuidedLoadExitFrame, expected: EXIT_FRAMES },
} as const;

describe.each(Object.entries(BUILDERS))('guided-load %s frame', (_name, { build, expected }) => {
  it('matches the pinned frame at the default sequence', () => {
    expect(Array.from(build())).toEqual([...expected.default]);
  });

  it.each(EXPLICIT_SEQUENCES)('matches the pinned frame at sequence %i', (sequence) => {
    expect(Array.from(build(sequence))).toEqual([...expected[sequence]]);
  });
});

describe('guided-load exported constants', () => {
  it('match the pinned values', () => {
    expect({
      PARAM_DIRECT_LOAD_SAFETY_CHECK,
      PARAM_DIRECT_LOAD_ST,
      PARAM_DIRECT_LOAD_COUNTDOWN,
      PARAM_DIRECT_LOAD_CTRL,
      GUIDED_LOAD_MODE_ARMED,
      GUIDED_LOAD_MODE_ACTIVE,
      GUIDED_LOAD_MODE_EXIT,
    }).toEqual(EXPORTED_CONSTANTS);
  });
});
