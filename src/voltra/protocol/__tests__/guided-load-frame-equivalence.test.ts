/**
 * Pinned output of the guided-load frame builders and the constants they
 * expose.
 *
 * The three builders are pure functions of a sequence number, so their whole
 * observable behaviour fits in a fixture. This file exists so that a change to
 * where those values come from — a protocol regen, a refactor of the module —
 * cannot alter what goes on the wire without a test failing.
 *
 * The fixture is a transcript, not documentation. Do not annotate the arrays,
 * and do not regenerate them to make a failing test pass: a diff here means the
 * emitted frame changed, which is the thing this file is here to catch. The
 * exit frame's bytes moved once on purpose, under VW-279, because that frame
 * was the defect.
 */
