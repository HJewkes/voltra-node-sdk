const EXPORTED_ACTION_CODES = {
  JustRow: 0x03,
  M50: 0x06,
  M100: 0x07,
  M500: 0x08,
  M1000: 0x09,
  M2000: 0x0a,
  M5000: 0x0b,
} as const;

describe.each(Object.keys(SCR_SWITCH_FRAMES) as Array<keyof typeof SCR_SWITCH_FRAMES>)(
  'rowing screen-switch %s frame',
  (key) => {
    const expected = SCR_SWITCH_FRAMES[key];
    const action = ROW_START_ACTION_CODES[key];

    it('matches the pinned frame at the default sequence', () => {
      expect(Array.from(buildRowScrSwitchFrame(action))).toEqual([...expected.default]);
    });

    it.each(EXPLICIT_SEQUENCES)('matches the pinned frame at sequence %i', (sequence) => {
      expect(Array.from(buildRowScrSwitchFrame(action, { sequence }))).toEqual([
        ...expected[sequence],
      ]);
    });
  }
);

describe('rowing vendor state-refresh frame', () => {
  it('matches the pinned frame at the default sequence', () => {
    expect(Array.from(buildVendorStateRefreshFrame())).toEqual([...VENDOR_REFRESH_FRAMES.default]);
  });

  it.each(EXPLICIT_SEQUENCES)('matches the pinned frame at sequence %i', (sequence) => {
    expect(Array.from(buildVendorStateRefreshFrame({ sequence }))).toEqual([
      ...VENDOR_REFRESH_FRAMES[sequence],
    ]);
  });
});

describe('rowing exported action codes', () => {
  it('match the pinned values', () => {
    expect(ROW_START_ACTION_CODES).toEqual(EXPORTED_ACTION_CODES);
  });
});
